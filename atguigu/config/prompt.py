# ============================================================
# 旅游领域标签抽取提示词（导入阶段）
#
# 为什么改成旅游专用：
# - 之前用“通用主体 + 元数据优先”，把所有成都文档压成“成都”，
#   丢失了 交通/美食/住宿/线路/景点 这些关键维度；
# - 现在只针对当前旅游领域，明确要求输出 entity/category/granularity；
# - 不读取、不依赖源文档里的 `## 元数据` 章节；
# - 以后换领域时替换这一组提示词即可。
# ============================================================
TRAVEL_LABEL_SYSTEM_PROMPT = (
    "你是旅游知识库的文档标注助手。请判断一份旅游文档主要覆盖的目的地、"
    "内容类别和粒度。"
)

TRAVEL_LABEL_TEMPLATE = """
文档标题：{file_title}

文档开头内容：
{context}

请只输出一个 JSON 对象，不要输出 Markdown 代码块，不要输出解释：
{{
  "entity": "这份文档主要覆盖的目的地/区域；无法判断时返回空字符串",
  "category": "景点/交通/美食/住宿/线路/综合 之一",
  "granularity": "city/region/poi/route/unknown 之一",
  "mentioned_entities": ["正文提到、但不是本文档主体的地点"],
  "confidence": 0.0
}}

规则：
1. entity 是这份文档主要覆盖的对象，不是正文里出现的所有地名；
2. category 只能从给定枚举里选，无法判断用“综合”；
3. granularity 表示文档粒度：城市/区域/景点/线路；
4. mentioned_entities 只放正文提到、但不是主体的地点；
5. 只根据标题和正文判断；不要假设、读取或依赖任何“元数据”章节；
6. confidence 是 0~1 的小数。
"""



# ============================================================
# 主体提取与问题改写提示词（查询阶段）
#
# 设计原则：
# 1. 不假设用户问的是“商品”，主体可以是地点、组织、作品、课程、主题等；
# 2. “型号/品牌/别名”只是补充信息，不是主体本身；
# 3. 输出字段名仍用 item_names，保持与现有 schema 兼容，
#    但它的语义是“主体名称列表”，不是狭义的“商品名”。
# ============================================================
ITEM_NAME_EXTRACT_SYSTEM_PROMPT = (
    "你是一个对话理解助手，负责从用户问题中识别核心主体（实体），"
    "并结合历史会话做指代消解。"
)

ITEM_NAME_EXTRACT_TEMPLATE = """
历史会话：
{history_text}

当前用户问题：
{original_query}

请识别用户当前正在询问的主体，并把问题改写成独立完整的句子。

概念说明：
- 主体：用户真正想了解的核心对象，可能是一个产品、设备、地点、组织、人物、作品、课程或主题。
- 补充信息：品牌、型号、别名、属性等。它们不是主体本身，但可以作为补充，帮助区分同名主体。

提取规则：
1. 只提取用户真正在问的主体；不要把路线经过的城市、举例、周边地名都列成主体。
2. 单主体问题 item_names 最多 1 个；只有明确对比/并列时才返回多个。
3. 如果当前问题使用代词（如“这个”“它”“那里”），结合历史做指代消解。
4. 主体去重；没有主体信息时 item_names 返回空列表。
5. category 从 ["景点", "交通", "美食", "住宿", "线路", "综合"] 中选一个；
   问题没有明显类别时返回空字符串。
6. 改写用户问题（rewritten_query），使其成为包含主体的独立完整问题。

请直接返回 JSON，不要使用 Markdown 代码块，格式如下：
{{
    "item_names": ["主体A"],
    "category": "景点/交通/美食/住宿/线路/综合 之一，或空字符串",
    "rewritten_query": "关于主体A的独立完整问题"
}}
"""


